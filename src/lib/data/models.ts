/** Visible models only — excludes models belonging to hidden brands. */
export const models: VehicleModel[] = allModels.filter(
  (m) => !getBrand(m.brandSlug)?.hidden
);

export function getModel(slug: string): VehicleModel | undefined {
  return models.find((m) => m.slug === slug);
}

export function getModelsByBrand(brandSlug: string): VehicleModel[] {
  return models.filter((m) => m.brandSlug === brandSlug);
}

export function getFeaturedModels(): VehicleModel[] {
  return models.filter((m) => m.isFeatured);
}

export function getNewModels(): VehicleModel[] {
  return models.filter((m) => m.isNew);
}

export interface ModelCategory {
  key: string;
  label: string;
  href: string;
  models: VehicleModel[];
}

export function getModelCategories(): ModelCategory[] {
  const categories: { key: string; label: string; href: string; match: (m: VehicleModel) => boolean }[] = [
    { key: "suv", label: "SUV", href: "/cars?body=SUV", match: (m) => m.bodyType === "SUV" },
    { key: "ev", label: "EV", href: "/cars?fuel=EV", match: (m) => m.fuelType === "EV" },
    { key: "mpv", label: "MPV", href: "/cars?body=MPV", match: (m) => m.bodyType === "MPV" },
    {
      key: "van-pickup",
      label: "Van & Pickup",
      href: "/cars?body=Van,Pickup",
      match: (m) => m.bodyType === "Van" || m.bodyType === "Pickup",
    },
  ];

  return categories
    .map((c) => ({ key: c.key, label: c.label, href: c.href, models: models.filter(c.match) }))
    .filter((c) => c.models.length > 0);
}
